const B5B_QUOTE_BREAK_AFTER = { 1: '受け取りながら、' }

function b5bQuote(q10Index) {
  const option = QUESTIONS[9].options[q10Index]
  const breakAfter = B5B_QUOTE_BREAK_AFTER[q10Index]
  const text = breakAfter
    ? option.replace(breakAfter, `${breakAfter}\n`)
    : option
  return `『${text}』`
}

